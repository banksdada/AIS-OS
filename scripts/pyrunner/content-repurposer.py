"""
AI OS agent worker — Content repurposer
Generated by the AI OS plugin. Reads the next message from this agent's
DataStore (pending_prompt), asks the AI, and saves the reply to its memory
(history), which the chat page picks up.

Reports each real run to the AI OS dashboard (started / ok / failed).
Idle runs report nothing, so the panel is not flooded.
"""

AGENT_KEY = "content-repurposer"
PROVIDER = "freellmapi"
MODEL = "auto"
BASE_URL = ""
SYSTEM_PROMPT = 'You are the Content Repurposer for webawesome.co.uk, a web\r\ndesign and AI automation agency. I give you ONE piece of source\r\nmaterial (a project case study, a call summary, a win, a lesson\r\nlearned) and you turn it into a week of marketing content.\r\n\r\nINPUT: one piece of source content. It may be raw notes.\r\n\r\nOUTPUT — produce exactly these 5 items, each clearly labelled:\r\n\r\n1. LINKEDIN POST (x2)\r\n   - Post A: story-style. Hook in line 1, 120-180 words, ends\r\n     with a soft question. No hashtags, no link.\r\n   - Post B: lesson-style. One specific lesson from the source,\r\n     actionable. 80-120 words.\r\n\r\n2. EMAIL NEWSLETTER BLOCK (150-200 words)\r\n   - Subject line + body. One case-study or insight, one\r\n     sentence CTA to book a call.\r\n\r\n3. BLOG OUTLINE (not full post)\r\n   - Working title, 4-5 H2 sections with 1-line descriptions\r\n     each. The human writes the full post.\r\n\r\n4. 3 HOOK LINES\r\n   - Three alternate opening lines any of the above could use.\r\n\r\n5. ONE-LINER\r\n   - A single sentence summarising the win, for use in\r\n     conversations ("Last month we...").\r\n\r\nRULES:\r\n- Sound like a real agency owner, not a marketing template.\r\n  Specific beats clever.\r\n- Include real numbers/details from the source when present.\r\n  Never invent metrics — if I don\'t give a number, don\'t make\r\n  one up.\r\n- No "In today\'s fast-paced world" type filler. Zero.\r\n- Web + AI automation is the positioning — tie each piece back\r\n  to it naturally, not forcedly.'
TOOLS = ['web_search']
MEMORY_ENABLED = False

import hashlib
import hmac
import json
import os
import re
import sys
import time
import urllib.request
from datetime import datetime

DEFAULT_BASE_URL = "https://opencode.ai/zen/v1"
DEFAULT_MODEL = "minimax-m2.5"

# ---------- AI OS dashboard reporting ----------
# Inlined so the script has no extra module to import: PyRunner runs each
# script standalone and cannot see a separate aios_report.py file.

AIOS_WEBHOOK_URL = "https://aios.webawesome.co.uk/webhook/pyrunner"


def report(agent, status, message=""):
    """Send one status event to the AI OS dashboard. Never raises."""
    secret = os.environ.get("PYRUNNER_WEBHOOK_SECRET", "")
    if not secret:
        print("AIOS report skipped: PYRUNNER_WEBHOOK_SECRET not set")
        return False
    try:
        data = {"agent": agent, "status": status, "message": str(message)[:500]}
        body = json.dumps(data).encode()
        ts = str(int(time.time()))
        signed = f"{ts}.".encode() + body
        sig = "sha256=" + hmac.new(secret.encode(), signed, hashlib.sha256).hexdigest()
        headers = {
            "Content-Type": "application/json",
            "X-AIOS-Timestamp": ts,
            "X-AIOS-Signature": sig,
        }
        req = urllib.request.Request(AIOS_WEBHOOK_URL, data=body, headers=headers, method="POST")
        with urllib.request.urlopen(req, timeout=20) as resp:
            print("AIOS report sent:", resp.status)
        return True
    except Exception as e:
        print("AIOS report failed:", e)
        return False


def now():
    return datetime.now().isoformat()


def datastore():
    from pyrunner_datastore import DataStore

    return DataStore(f"ai_os:agent_{AGENT_KEY}")


def pick_model():
    env_model = os.environ.get("AI_MODEL")
    if env_model:
        return env_model
    if PROVIDER != "claude" and MODEL and MODEL != "auto":
        return MODEL
    return DEFAULT_MODEL


def fetch_pages(text):
    """If web_fetch is on, read any web addresses in the message."""
    if "web_fetch" not in TOOLS:
        return ""
    urls = []
    for u in re.findall(r"https?://[^\s<>\"'\u2018\u2019\u201c\u201d)\]]+", text):
        u = u.rstrip(".,;:!?")
        if u not in urls:
            urls.append(u)
    if not urls:
        found = re.findall(r"\b((?:[a-z0-9-]+\.)+[a-z]{2,}(?:/[^\s<>\u2018\u2019\u201c\u201d]*)?)", text.lower())
        urls = ["https://" + f.rstrip(".,;:!?") for f in found[:1]]
    if not urls:
        return ""
    chunks = []
    ok = 0
    for url in urls[:3]:
        try:
            req = urllib.request.Request(
                url, headers={"User-Agent": "Mozilla/5.0 (compatible; WebAwesomeBot/1.0)"}
            )
            html = urllib.request.urlopen(req, timeout=25).read().decode("utf-8", "ignore")
            html = re.sub(r"(?is)<(script|style|noscript).*?</\1>", " ", html)
            title = re.search(r"(?is)<title>(.*?)</title>", html)
            body = re.sub(r"(?s)<[^>]+>", " ", html)
            body = re.sub(r"\s+", " ", body).strip()[:6000]
            chunks.append(
                f"PAGE {url}\nTITLE: {title.group(1).strip() if title else ''}\nTEXT: {body}"
            )
            ok += 1
        except Exception as exc:  # noqa: BLE001
            print(f"fetch failed for {url}: {exc}", file=sys.stderr)
            chunks.append(f"PAGE {url}\nCOULD NOT BE FETCHED: {exc}")
    if ok == 0:
        return (
            "\n\nIMPORTANT: My attempt to read the web page(s) FAILED ("
            + "; ".join(chunks)
            + "). This is a problem on my side, NOT evidence the site is broken. "
            "Do NOT audit, score or judge the site. Reply only with a short note that the "
            "page could not be read, say why, and ask the user to check the web address "
            "and try again."
        )
    return (
        "\n\nWEB PAGES READ FOR YOU (use only this; say if something is missing):\n"
        + "\n\n".join(chunks)
    )


def call_llm(history, extra):
    api_key = (
        os.environ.get("AI_API_KEY")
        or os.environ.get("OPENCODE_API_KEY")
        or os.environ.get("FREE_LLMAPI_KEY")
        or os.environ.get("OPENAI_API_KEY")
        or ""
    )
    if not api_key:
        raise RuntimeError(
            "No API key. Grant the OPENCODE_API_KEY secret to this script in PyRunner."
        )
    base_url = (BASE_URL or os.environ.get("AI_BASE_URL") or DEFAULT_BASE_URL).rstrip("/")

    messages = [{"role": "system", "content": SYSTEM_PROMPT}]
    # Memory off: every request starts clean (only the latest message is sent).
    recent = history[-10:] if MEMORY_ENABLED else history[-1:]
    for m in recent:
        messages.append({"role": m["role"], "content": m["content"]})
    if extra:
        messages[-1] = {"role": "user", "content": messages[-1]["content"] + extra}

    payload = json.dumps({"model": pick_model(), "messages": messages}).encode()
    req = urllib.request.Request(
        base_url + "/chat/completions",
        payload,
        {
            "Content-Type": "application/json",
            "Authorization": "Bearer " + api_key,
            "User-Agent": "Mozilla/5.0 (compatible; WebAwesomeBot/1.0)",
        },
    )
    raw = urllib.request.urlopen(req, timeout=150).read().decode()
    text = json.loads(raw)["choices"][0]["message"]["content"] or ""
    text = re.sub(r"```.*?```", "", text, flags=re.S).strip()
    if not text:
        raise RuntimeError("The AI returned an empty reply.")
    return text


def main():
    store = datastore()
    pending = store.get("pending_prompt") or ""
    history = store.get("history") or []
    if not isinstance(history, list):
        history = []

    print(f"agent={AGENT_KEY} model={pick_model()} tools={TOOLS}")

    if not pending:
        print("no pending prompt - idle (send a chat message, then run)")
        return 0

    report(AGENT_KEY, "started", f"prompt received ({len(pending)} chars)")

    history.append({"role": "user", "content": pending, "at": now()})
    try:
        reply = call_llm(history, fetch_pages(pending))
    except Exception as exc:  # noqa: BLE001
        detail = ""
        if hasattr(exc, "read"):
            try:
                detail = exc.read().decode()[:300]
            except Exception:  # noqa: BLE001
                pass
        msg = f"Sorry, I couldn't get an answer: {exc} {detail}".strip()
        print(msg, file=sys.stderr)
        store["pending_prompt"] = None
        report(AGENT_KEY, "failed", str(exc)[:300])
        return 1

    history.append({"role": "assistant", "content": reply, "at": now()})
    store["history"] = history[-40:]
    store["pending_prompt"] = None
    print(f"reply: {reply}")
    report(AGENT_KEY, "ok", f"reply generated: {reply[:120]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
